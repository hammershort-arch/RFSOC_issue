#!/usr/bin/env python3
"""mk_xsdb_fir_gain.py — 把 15_自動化校正資料 產生的 fir_chN_v2.tcl（reg_fir_tap 行）轉成 RFSoC_TX v1.0.0（RegMap v8）用的 xsdb script。
15_自動化校正資料/04_xsdb/reference/reg_rt.tcl 是 RegMap v7 + 舊位址（ch1 0xA0020000），不能直接用在 v1.0.0；這裡改用 v8 offset：
  mem0 0x000 fir_enable、mem1~16 0x004~0x040 fir_tap00~15（[31:16] Q, [15:0] I）、mem20 0x050 gain_index_mode_sel、mem21 0x054 gain_index_manual、
  mem38 0x098 bypass_axis_iq、mem39 0x09C signal_source_select；ch N base = 0xA009_0000 + 0x1000 × (N−1)。
寫入順序（Register_Map.md §寫入順序）：fir_enable=0 → 16 taps → gain_index_manual → gain_index_mode_sel → [mem39] → mem38 → fir_enable=1，全部讀回比對。
用法: python3 -I mk_xsdb_fir_gain.py <fir_chN_v2.tcl> <out.tcl> --ch 1-8 --mode-sel 1 --manual 0 --bypass 0 [--src 0|1] [--port 2542]
      xsdb <out.tcl>    （2026-10-19）"""
import argparse, re
ap = argparse.ArgumentParser()
ap.add_argument("fir"); ap.add_argument("out")
ap.add_argument("--ch", default="1-8"); ap.add_argument("--port", default="2542")
ap.add_argument("--mode-sel", type=int, default=1); ap.add_argument("--manual", type=int, default=0, help="raw S6.4（0 = 0 dB）")
ap.add_argument("--bypass", type=int, default=0); ap.add_argument("--src", type=int, default=None, help="mem39；不給就不動")
a = ap.parse_args()
taps = {}
for l in open(a.fir, encoding="utf-8"):
    m = re.match(r"\s*reg_fir_tap\s+(\d+)\s+(-?\d+)\s+(-?\d+)", l)
    if m: taps[int(m[1])] = ((int(m[3]) & 0xFFFF) << 16) | (int(m[2]) & 0xFFFF)
assert sorted(taps) == list(range(16)), "需要 16 個 reg_fir_tap"
lo, hi = (int(x) for x in a.ch.split("-")) if "-" in a.ch else (int(a.ch),) * 2
writes = [(0x000, 0)] + [(0x004 + 4 * t, taps[t]) for t in range(16)] + [(0x054, a.manual & 0x7FF), (0x050, a.mode_sel)]
if a.src is not None: writes.append((0x09C, a.src))
writes += [(0x098, a.bypass), (0x000, 1)]
L = [f"# generated by mk_xsdb_fir_gain.py from {a.fir}", f"connect -xvc-url TCP:192.168.68.41:{a.port}", "after 2500",
     'targets -set -nocase -filter {name =~ "PSU"}', "set err 0",
     "set W {" + " ".join(f"0x{o:03X} 0x{v:08X}" for o, v in writes) + "}",
     f"for {{set n {lo}}} {{$n <= {hi}}} {{incr n}} {{",
     "  set base [expr {0xA0090000 + 0x1000*($n-1)}]",
     "  set tap7 [lindex [mrd -force -value [expr {$base + 0x20}] 1] 0]",
     "  foreach {o v} $W { mwr -force [expr {$base + $o}] $v }",
     "  set bad {}",
     "  foreach {o v} $W { set r [lindex [mrd -force -value [expr {$base + $o}] 1] 0]; if {$o != 0 && $r != $v} { lappend bad [format \"0x%03X=0x%X(exp 0x%X)\" $o $r $v] } }",
     "  set rd {}; foreach o {0x000 0x050 0x054 0x098 0x09C} { lappend rd [format 0x%X [lindex [mrd -force -value [expr {$base + $o}] 1] 0]] }",
     "  if {[llength $bad]} { incr err }",
     "  puts [format \"ch%d tap7_before=0x%08X  fir_en/mode_sel/manual/bypass/src = %s  mismatch: %s\" $n $tap7 [join $rd /] [expr {[llength $bad] ? $bad : \"none\"}]]",
     "}",
     'foreach t [targets -target-properties] { if {[dict get $t name] eq "Cortex-A53 #0"} { puts "A53#0 [dict get $t state_reason]" } }',
     'puts "ERRORS $err"', "disconnect", ""]
open(a.out, "w").write("\n".join(L))
print("written", a.out, "taps:", " ".join(f"{taps[t]:08X}" for t in range(16)))
